class UpdateTests(PersonalCase):
    def test_update_keeps_additions_replacements_and_disables(self):
        self.ok("overlay", "add-rule", "--id", "mine", "-", stdin=rule_file("My rule", "Mine."))
        self.ok("overlay", "replace-rule", "beta", "-", stdin=rule_file("Beta, mine", "My beta."))
        self.ok("overlay", "disable-rule", "gamma")
        self.ok("overlay", "add-verifier", "-", stdin=self.verifier_text("my-check", "My check"))
        self.ok("overlay", "replace-verifier", "shellcheck", "-", stdin=self.verifier_text("shellcheck", "Shellcheck, my way"))
        self.ok("overlay", "replace-verifier", "semgrep-not-there", "-", stdin=self.verifier_text("semgrep-not-there")) \
            if False else None
        self.ok("overlay", "disable-verifier", "mutmut")
        self.ok("overlay", "replace-recipe", "bugfix", "-", stdin=self.recipe_text("bugfix", "Bugfix, my way"))
        base_hashes = overlay.bases()
        self.assertEqual(set(base_hashes), {"rule:beta", "verifier:shellcheck", "recipe:bugfix"})
        # the product moves on: alpha unchanged, beta changed, gamma removed, delta new; shellcheck changed, bugfix unchanged
        p2 = self.make_product("p2", [RULES[0], ("beta", "Beta rule", "Do beta things, newly.\n\nWhy: beta."),
                                      ("delta", "Delta rule", "Do delta things.\n\nWhy: delta.")], edit_library=True)
        sc = os.path.join(p2, "verifiers", "safety", "shellcheck.md")
        open(sc, "w").write(open(sc).read().replace("title:", "title: (new) ", 1))
        self.use_product(p2)
        out = self.ok("update", "--post").stdout
        self.assertIn("kept your version of rule beta", out)
        self.assertIn("kept your version of verifier shellcheck", out)
        self.assertNotIn("bugfix", out.split("doctor:")[0].replace("backup", ""))
        g = self.generated()
        self.assertIn("Beta, mine", g)
        self.assertNotIn("newly", g)
        self.assertIn("Alpha rule", g)
        self.assertIn("Delta rule", g)          # the product's new rule arrives
        self.assertIn("My rule", g)             # the addition survives
        self.assertNotIn("Gamma", g)            # removed by the product and disabled by the person
        libs = self.ok("verifiers", "--section", "safety").stdout
        self.assertRegex(libs, r"shellcheck .*Shellcheck, my way")
        self.assertIn("my-check", libs)
        self.assertNotRegex(self.ok("verifiers").stdout, r"\n  mutmut ")
        queue = [json.loads(l) for l in open(os.path.join(self.data, "retest.jsonl"))]
        self.assertEqual(sorted((q["kind"], q["id"]) for q in queue), [("rule", "beta"), ("verifier", "shellcheck")])
        q = {q["id"]: q for q in queue}
        self.assertEqual(q["beta"]["old_base_hash"], base_hashes["rule:beta"])
        self.assertEqual(q["beta"]["new_base_hash"], overlay.base_hash("rule", "beta"))
        self.assertNotEqual(q["beta"]["old_base_hash"], q["beta"]["new_base_hash"])
        self.assertEqual(q["shellcheck"]["new_base_hash"], overlay.base_hash("verifier", "shellcheck"))
        # a second update changes nothing and queues nothing new
        self.ok("update", "--post")
        self.assertEqual(len(open(os.path.join(self.data, "retest.jsonl")).read().splitlines()), 2)
        self.assertEqual(self.generated(), g)
        self.assertTrue(os.listdir(os.path.join(self.data, "backups")))

    def make_origin_and_clone(self):
        """A product that is a real git clone of an origin, so `sisi update` can fetch and fast-forward it."""
        origin = os.path.join(self.tmp, "origin")
        shutil.copytree(REPO, origin, ignore=shutil.ignore_patterns(".git", "__pycache__", "tests", ".sisi", "docs", "verifiers", "done"))
        shutil.copytree(os.path.join(REPO, "verifiers"), os.path.join(origin, "verifiers"))
        shutil.copytree(os.path.join(REPO, "done"), os.path.join(origin, "done"))
        g = lambda d, *a: subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", "-C", d] + list(a), check=True, capture_output=True)
        subprocess.run(["git", "init", "-q", "-b", "main", origin], check=True)
        g(origin, "add", "-A")
        g(origin, "commit", "-q", "-m", "one")
        clone = os.path.join(self.tmp, "clone")
        subprocess.run(["git", "clone", "-q", origin, clone], check=True, capture_output=True)
        return origin, clone, g

    def test_update_refusals_and_fast_forward(self):
        origin, clone, g = self.make_origin_and_clone()
        self.use_product(clone)
        # no upstream
        g(clone, "checkout", "-q", "-b", "local")
        r = self.sisi("update")
        self.assertEqual(r.returncode, 1)
        self.assertIn("no upstream", r.stdout)
        g(clone, "checkout", "-q", "main")
        # local changes: refused, nothing discarded
        core = os.path.join(clone, "canon", "core.md")
        orig = open(core).read()
        open(core, "a").write("\nlocal edit\n")
        r = self.sisi("update")
        self.assertEqual(r.returncode, 1)
        self.assertIn("local changes", r.stdout)
        self.assertTrue(open(core).read().endswith("local edit\n"))
        open(core, "w").write(orig)
        # a person's replacement, then the origin changes that rule
        rid = "know-done"
        self.ok("overlay", "replace-rule", rid, "-", stdin=rule_file("Know it, my way", "My text."))
        text = open(os.path.join(origin, "canon", "core.md")).read()
        open(os.path.join(origin, "canon", "core.md"), "w").write(text.replace("Skip the contract for small edits", "Skip the contract for tiny edits"))
        g(origin, "commit", "-q", "-am", "two")
        r = self.ok("update")
        self.assertIn("->", r.stdout)
        self.assertIn("tiny edits", open(core).read())
        self.assertIn("kept your version of rule know-done", r.stdout)
        self.assertIn("Know it, my way", self.generated())
        self.assertIn("rulebook rebuilt", r.stdout)
        self.assertIn("rulebook", r.stdout.split("doctor:")[1])
        r = self.ok("update")
        self.assertIn("already up to date", r.stdout)
        self.assertEqual(len([l for l in open(os.path.join(self.data, "retest.jsonl"))]), 1)

    def test_update_refuses_outside_a_git_clone(self):
        r = self.sisi("update")
        self.assertEqual(r.returncode, 1)
        self.assertIn("not a git clone", r.stdout)


class MigrationTests(PersonalCase):
    LESSONS = [dict(aim="verified", moment="ran pytest and it passed without the new test", cause="the test never failed",
                    change_kind="rule", change="Always watch a new test fail without the change first", target=None),
               dict(aim="speed", moment="re-read the same large log three times in a row", cause="no summary kept",
                    change_kind="verifier", change="Note the log tool in the field notes for the verifier", target="fuzz")]

    def legacy_state(self, extra_lesson=False):
        """Lay out an old-style installation: personal files in the state dir, oracle and notes in the product."""
        os.makedirs(os.path.join(self.state, "backups"))
        db = os.path.join(self.state, "retro.db")
        with unittest.mock.patch.object(retro, "db_path", return_value=db):
            con = retro.connect()
            for f in self.LESSONS + ([dict(aim="intent", moment="built the wrong thing for a day", cause="no check with the human",
                                           change_kind="rule", change="Confirm the goal in one line before starting", target=None)] if extra_lesson else []):
                retro.new_lesson(con, dict(f), self.proj, None)
            con.commit()
            con.close()
        json.dump([self.proj], open(os.path.join(self.state, "trusted.json"), "w"))
        json.dump({"verify": {"fast_limit_s": 9}}, open(os.path.join(self.state, "config.json"), "w"))
        for n, t in (("learn-quarantine.jsonl", "quarantined"), ("notes.jsonl", "a note"), ("proposals.jsonl", "a proposal")):
            open(os.path.join(self.state, n), "w").write(json.dumps({"text": t}) + "\n")
        open(os.path.join(self.state, "backups", "ab-CLAUDE.md.orig"), "w").write("original\n")
        json.dump({"dirs": [], "files": {"/x/CLAUDE.md": {"backup": "ab-CLAUDE.md.orig"}}}, open(os.path.join(self.state, "manifest.json"), "w"))
        for n in ("harvest.db", "results.jsonl"):
            open(os.path.join(self.state, n), "w").write("scratch\n")
        os.makedirs(os.path.join(self.p1, "notes"))
        open(os.path.join(self.p1, "notes", "fuzz.md"), "w").write("# Field notes for fuzz\n\n- 2026-11-01: a field note (aim: speed; seen 2 times; lesson 2)\n")
        open(os.path.join(self.p1, "canon", "oracle.md"), "w").write("# oracle\n\nThe person wants things asked once.\n")

    def lessons_of(self, path):
        con = sqlite3.connect(path)
        con.row_factory = sqlite3.Row
        try:
            return [dict(r) for r in con.execute("SELECT * FROM lessons ORDER BY id")], \
                   [dict(r) for r in con.execute("SELECT * FROM occurrences ORDER BY id")]
        finally:
            con.close()

    def test_migrate_moves_everything_once_without_losing_or_duplicating(self):
        self.legacy_state()
        before = self.lessons_of(os.path.join(self.state, "retro.db"))
        self.assertEqual(len(before[0]), 2)

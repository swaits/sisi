    def test_one_commit_per_change_and_revert_restores_bytes(self):
        self.ok("build-canon")
        n0 = len(self.git_log())
        steps = [(("add-rule", "--id", "delta", "-"), rule_file("Delta", "Body.")),
                 (("replace-rule", "alpha", "-"), rule_file("Alpha, mine", "Mine.")),
                 (("disable-rule", "gamma"), ""),
                 (("add-verifier", "-"), self.verifier_text("my-check")),
                 (("disable-recipe", "release"), "")]
        gens = [self.generated()]
        for args, text in steps:
            self.ok("overlay", *args, stdin=text)
            gens.append(self.generated())
            self.assertEqual(len(self.git_log()), n0 + len(gens) - 1)
        self.assertEqual(self.git_log()[0], "overlay: disable recipe release")
        # revert the disable-rule commit: the rulebook is exactly what it was after the replace-rule
        c = pdata.git("log", "--format=%h", "--grep=disable rule gamma").stdout.split()[0]
        self.ok("overlay", "revert", c)
        self.assertEqual(self.generated().split("\n")[1:], gens[2].split("\n")[1:])
        # reverting the add of delta as well gives the state after replace-rule minus delta; reverting all gives the base
        for subj in ("add rule delta", "replace rule alpha"):
            self.ok("overlay", "revert", pdata.git("log", "--format=%h", "--grep=overlay: " + subj).stdout.split()[0])
        base = core_text(RULES)
        want = overlay.render()
        self.assertEqual(self.generated(), want)
        self.assertEqual(self.generated().split("\n", 2)[2].count("## "), 3)
        # a non-overlay commit cannot be reverted here
        first = pdata.git("rev-list", "--max-parents=0", "HEAD").stdout.split()[0]
        self.assertEqual(self.sisi("overlay", "revert", first).returncode, 1)


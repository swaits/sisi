class ProductIsReadOnlyTests(PersonalCase):
    def test_no_command_writes_inside_the_product(self):
        prod = os.path.join(self.tmp, "product")
        shutil.copytree(REPO, prod, ignore=shutil.ignore_patterns(".git", "__pycache__", "tests", ".sisi", ".agent-work"))
        def unlock():
            for dp, dns, fns in os.walk(prod):
                os.chmod(dp, 0o755)
                for n in fns:
                    os.chmod(os.path.join(dp, n), 0o644)
        self.addCleanup(unlock)
        from test_wiring import snapshot
        before = snapshot(prod)
        for dp, dns, fns in os.walk(prod, topdown=False):
            for n in fns:
                os.chmod(os.path.join(dp, n), 0o555 if n == "sisi" else 0o444)
            os.chmod(dp, 0o555)
        os.makedirs(os.path.join(self.home, ".claude"))
        os.makedirs(os.path.join(self.home, ".codex"))
        self.git_init()
        binp = os.path.join(prod, "bin", "sisi")
        def run(*a, stdin=None):
            # output goes to files, not pipes: a detached background worker must not hold this test open
            with open(os.path.join(self.tmp, "o.txt"), "w+") as out, open(os.path.join(self.tmp, "e.txt"), "w+") as err:
                p = subprocess.Popen([sys.executable, binp] + list(a), cwd=self.proj, stdin=subprocess.PIPE, stdout=out, stderr=err,
                                     text=True, env=dict(os.environ, PYTHONFAULTHANDLER="1"))
                try:
                    p.communicate(stdin, timeout=int(os.environ.get("RO_T", "30")))
                except subprocess.TimeoutExpired:
                    tree = subprocess.run(["ps", "-eo", "pid,ppid,stat,etime,args", "--forest"], capture_output=True, text=True).stdout
                    p.send_signal(signal.SIGABRT)  # faulthandler prints the Python stack
                    time.sleep(1)
                    p.kill()
                    err.seek(0)
                    self.fail("hung: sisi %s\nstderr:\n%s\nprocess tree:\n%s" % (a, err.read(), tree))
                out.seek(0), err.seek(0)
                return subprocess.CompletedProcess(a, p.returncode, out.read(), err.read())
        gate_in = json.dumps({"session_id": "s1", "cwd": self.proj, "stop_hook_active": False})
        cmds = [("install",), ("doctor",), ("tick", "--tool", "t"), ("build-canon",), ("status",),
                ("overlay", "add-rule", "--id", "z", "-"), ("overlay", "diff"), ("overlay", "disable-rule", "z"),
                ("learn", "--scope", "everywhere", "x"), ("lessons", "export"), ("verifiers", "show", "shellcheck"),
                ("contract", "init", "--goal", "g"), ("verify",), ("migrate",), ("update",),
                ("export", os.path.join(self.tmp, "e.tar.gz")), ("gate",), ("uninstall",)]
        for c in cmds:
            r = run(*c, stdin=rule_file("Z", "Zed.") if c[:2] == ("overlay", "add-rule") else (gate_in if c == ("gate",) else None))
            self.assertNotIn("Permission denied", r.stderr + r.stdout, c)
            self.assertNotIn("Traceback", r.stderr, (c, r.stderr))
        r = run("retro", *LessonDumpTests.RETRO)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertEqual(snapshot(prod), before)
        self.assertTrue(os.path.exists(os.path.join(self.state, "pycache")), "bytecode goes to the scratch dir")


